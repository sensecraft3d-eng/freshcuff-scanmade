let lang = 'en';
const listeners = [];
export function getLang() { return lang; }
export function t(key, vars) {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  return s;
}
export function fmtNum(v, digits = 1) {
  if (!Number.isFinite(v)) return '—';
  return new Intl.NumberFormat(lang === 'pt' ? 'pt-BR' : 'en-GB', {minimumFractionDigits: digits, maximumFractionDigits: digits}).format(v);
}
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.setAttribute('placeholder', t(el.dataset.i18nPh)); });
  root.querySelectorAll('[data-i18n-alt]').forEach(el => { el.setAttribute('alt', t(el.dataset.i18nAlt)); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.dataset.i18nTitle)); });
}
export function setLang(l) {
  lang = STRINGS[l] ? l : 'en';
  document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
  document.title = t('doc_title');
  try { localStorage.setItem('fc_lang', lang); } catch (e) { /* private mode */ }
  applyI18n();
  listeners.forEach(f => f(lang));
}
export function onLang(f) { listeners.push(f); }
export function initialLang() {
  const q = new URLSearchParams(location.search).get('lang');
  if (q && STRINGS[q]) return q;
  try { const s = localStorage.getItem('fc_lang'); if (s && STRINGS[s]) return s; } catch (e) { /* ignore */ }
  return 'en';   // English first; Portuguese via the toggle (or ?lang=pt)
}
